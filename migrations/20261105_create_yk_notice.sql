CREATE TABLE IF NOT EXISTS yk_notice (
    noticeNo INT NOT NULL AUTO_INCREMENT,
    noticeTitle VARCHAR(200) NOT NULL,
    noticeContent LONGTEXT NOT NULL,
    userNo INT NOT NULL,
    regDate DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    modDate DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (noticeNo),
    KEY idx_yk_notice_regDate (regDate)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
